#!/usr/bin/env python3
"""Print, insert or check the generated facts block of a Unity project's PROJECT.md.

Reads only (never writes Unity files):
  ProjectSettings/ProjectVersion.txt, ProjectSettings/ProjectSettings.asset,
  ProjectSettings/GraphicsSettings.asset, ProjectSettings/QualitySettings.asset,
  ProjectSettings/EditorBuildSettings.asset, Packages/manifest.json,
  Packages/packages-lock.json, Assets/**/*.asmdef, Assets/**/*.meta (GUID lookup),
  Library/PackageCache/<git package>@*/package.json (optional, version of git packages).

Modes:
  (default)          print the facts block (markdown, between markers) to paste into PROJECT.md
  --json             print the facts as JSON
  --check [FILE]     compare FILE (default <root>/PROJECT.md) with the project; exit 1 on drift
  --update [FILE]    rewrite the block in FILE (between the markers) with fresh facts
  --init [FILE]      create FILE from references/PROJECT.template.md with a fresh block (refuses to overwrite)

Exit codes: 0 OK, 1 drift / check failed, 2 usage or setup error.
Last line is machine-readable: "RESULT: OK", "RESULT: DRIFT <n>", "RESULT: FAIL <reason>".
Python 3.9+ stdlib only.
"""
import argparse
import json
import os
import re
import sys

BEGIN = "<!-- project-snapshot:begin (generated by project_snapshot.py; refresh with --update, do not hand-edit) -->"
END = "<!-- project-snapshot:end -->"
BEGIN_RE = re.compile(r"<!--\s*project-snapshot:begin.*?-->")
END_RE = re.compile(r"<!--\s*project-snapshot:end\s*-->")

# Script GUIDs of URP types (stable across URP 17.x package versions).
RENDERER_SCRIPT_GUIDS = {
    "11145981673336645838492a2d98e247": "2D Renderer",
    "de640fe3d0db1804a85f9fc8f5cadab6": "Universal Renderer",
}
URP_ASSET_SCRIPT_GUID = "bf2edee5c58d82540a51f03df9d42094"

DEFAULT_TREE_EXCLUDES = ["Screenshots", "_Recovery", "TextMesh Pro", "Samples", "StreamingAssets/aa"]
INPUT_HANDLERS = {"0": "Input Manager (old)", "1": "Input System Package (new)", "2": "Both"}
SECRET_PATTERNS = [
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{30,}\b"),
    re.compile(r"\bsk-[A-Za-z0-9_\-]{20,}\b"),
    re.compile(r"\bxox[abprs]-[A-Za-z0-9\-]{10,}\b"),
    re.compile(r"(?i)\b(password|passwd|secret|token|api[_-]?key|private[_-]?key)\b\s*[:=]\s*(?![<$*\[]|env\b|none\b|n/a\b)\S{6,}"),
]
TREE_CHILD_CAP = 40


def fail(msg, code=2):
    print("ERROR: " + msg, file=sys.stderr)
    print("RESULT: FAIL " + msg)
    sys.exit(code)


def read(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def find_root(start):
    cur = os.path.abspath(start)
    while True:
        if os.path.isfile(os.path.join(cur, "ProjectSettings", "ProjectVersion.txt")):
            return cur
        parent = os.path.dirname(cur)
        if parent == cur:
            return None
        cur = parent


def guid_of(ref_text):
    m = re.search(r"guid:\s*([0-9a-f]{32})", ref_text or "")
    return m.group(1) if m else None


class GuidIndex:
    """Lazy GUID -> asset path lookup over Assets/**/*.meta."""

    def __init__(self, root):
        self.root = root
        self.map = None

    def path(self, guid):
        if not guid:
            return None
        if self.map is None:
            self.map = {}
            assets = os.path.join(self.root, "Assets")
            for dirpath, dirnames, filenames in os.walk(assets):
                dirnames[:] = [d for d in dirnames if not d.startswith(".")]
                for fn in filenames:
                    if not fn.endswith(".meta"):
                        continue
                    full = os.path.join(dirpath, fn)
                    try:
                        with open(full, "r", encoding="utf-8", errors="replace") as fh:
                            head = fh.read(300)
                    except OSError:
                        continue
                    g = re.search(r"^guid:\s*([0-9a-f]{32})", head, re.M)
                    if g:
                        self.map[g.group(1)] = os.path.relpath(full[:-5], self.root).replace(os.sep, "/")
        return self.map.get(guid)


def unity_version(root):
    txt = read(os.path.join(root, "ProjectSettings", "ProjectVersion.txt")) or ""
    m = re.search(r"m_EditorVersionWithRevision:\s*(.+)", txt) or re.search(r"m_EditorVersion:\s*(.+)", txt)
    return m.group(1).strip() if m else "unknown"


def player_settings(root):
    txt = read(os.path.join(root, "ProjectSettings", "ProjectSettings.asset")) or ""

    def val(key):
        m = re.search(r"^\s*" + key + r":\s*(.*)$", txt, re.M)
        return m.group(1).strip() if m else ""

    handler = val("activeInputHandler")
    return {
        "product": val("productName") or "unknown",
        "company": val("companyName") or "unknown",
        "input": INPUT_HANDLERS.get(handler, "Input Manager (old)" if not handler else "unknown (" + handler + ")"),
    }


def renderer_kind(root, path):
    txt = read(os.path.join(root, path)) or ""
    g = guid_of(re.search(r"m_Script:.*", txt).group(0)) if re.search(r"m_Script:.*", txt) else None
    if g in RENDERER_SCRIPT_GUIDS:
        return RENDERER_SCRIPT_GUIDS[g]
    if "m_LightBlendStyles" in txt:
        return "2D Renderer"
    return "other"


def render_pipeline(root, gidx):
    gs = read(os.path.join(root, "ProjectSettings", "GraphicsSettings.asset")) or ""
    m = re.search(r"m_CustomRenderPipeline:\s*(\{[^}]*\})", gs)
    default_path = gidx.path(guid_of(m.group(1))) if m else None
    qs = read(os.path.join(root, "ProjectSettings", "QualitySettings.asset")) or ""
    levels = []
    for block in re.split(r"\n\s*- serializedVersion:", qs)[1:]:
        n = re.search(r"^\s*name:\s*(.*)$", block, re.M)
        p = re.search(r"^\s*customRenderPipeline:\s*(\{[^}]*\})", block, re.M)
        levels.append((n.group(1).strip() if n else "?", gidx.path(guid_of(p.group(1))) if p else None))
    cur = re.search(r"m_CurrentQuality:\s*(\d+)", qs)
    cur_idx = int(cur.group(1)) if cur else 0
    current_name = levels[cur_idx][0] if 0 <= cur_idx < len(levels) else "?"
    by_asset = {}
    for name, path in levels:
        by_asset.setdefault(path or "none", []).append(name)
    assets = sorted(set([p for _, p in levels if p] + ([default_path] if default_path else [])))
    renderers = []
    for a in assets:
        txt = read(os.path.join(root, a)) or ""
        lst = re.search(r"m_RendererDataList:\s*\n((?:\s*- \{[^}]*\}\s*\n)+)", txt)
        if lst:
            for ref in re.findall(r"\{[^}]*\}", lst.group(1)):
                rp = gidx.path(guid_of(ref))
                if rp and rp not in [r[0] for r in renderers]:
                    renderers.append((rp, renderer_kind(root, rp)))
    return {
        "default": default_path or "none",
        "quality_current": current_name,
        "quality_levels": len(levels),
        "by_asset": {k: v for k, v in sorted(by_asset.items())},
        "renderers": renderers,
    }


def packages(root):
    man_txt = read(os.path.join(root, "Packages", "manifest.json"))
    if man_txt is None:
        return [], []
    try:
        man = json.loads(man_txt)
    except ValueError as e:
        fail("Packages/manifest.json is not valid JSON: %s" % e)
    lock = {}
    lock_txt = read(os.path.join(root, "Packages", "packages-lock.json"))
    if lock_txt:
        try:
            lock = json.loads(lock_txt).get("dependencies", {})
        except ValueError:
            lock = {}
    rows = []
    for name, req in sorted(man.get("dependencies", {}).items()):
        if name.startswith("com.unity.modules."):
            continue
        entry = lock.get(name, {})
        source = entry.get("source", "?")
        resolved = entry.get("version", "?")
        if source == "git":
            h = (entry.get("hash") or "")[:8]
            ver = git_pkg_version(root, name)
            resolved = (ver + " " if ver else "") + "@" + (h or "?")
        elif source in ("embedded", "local"):
            ver = local_pkg_version(root, name, req)
            resolved = ver or resolved
        rows.append({"name": name, "requested": req, "resolved": resolved, "source": source})
    regs = ["%s (%s)" % (r.get("name", "?"), r.get("url", "?")) for r in man.get("scopedRegistries", [])]
    return rows, regs


def git_pkg_version(root, name):
    cache = os.path.join(root, "Library", "PackageCache")
    try:
        for d in sorted(os.listdir(cache)):
            if d.startswith(name + "@"):
                txt = read(os.path.join(cache, d, "package.json"))
                if txt:
                    try:
                        return json.loads(txt).get("version")
                    except ValueError:
                        return None
    except OSError:
        return None
    return None


def local_pkg_version(root, name, req):
    cands = [os.path.join(root, "Packages", name, "package.json")]
    if isinstance(req, str) and req.startswith("file:"):
        cands.insert(0, os.path.join(root, "Packages", req[5:], "package.json"))
    for c in cands:
        txt = read(c)
        if txt:
            try:
                return json.loads(txt).get("version")
            except ValueError:
                return None
    return None


def asmdefs(root):
    rows = []
    assets = os.path.join(root, "Assets")
    for dirpath, dirnames, filenames in os.walk(assets):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and not d.endswith("~"))
        for fn in sorted(filenames):
            if not fn.endswith(".asmdef"):
                continue
            full = os.path.join(dirpath, fn)
            txt = read(full) or "{}"
            try:
                data = json.loads(txt)
            except ValueError:
                data = {}
            refs = " ".join(data.get("references", []))
            pre = " ".join(data.get("precompiledReferences", []))
            defs = " ".join(data.get("defineConstraints", []))
            editor_only = data.get("includePlatforms", []) == ["Editor"]
            is_test = ("UNITY_INCLUDE_TESTS" in defs or "nunit.framework" in pre or "TestRunner" in refs)
            if is_test:
                kind = "test-editmode" if editor_only else "test-playmode"
            else:
                kind = "editor" if editor_only else "runtime"
            folder = os.path.relpath(dirpath, root).replace(os.sep, "/")
            rows.append({"name": data.get("name", fn[:-7]), "folder": folder, "kind": kind})
    rows.sort(key=lambda r: r["name"])
    return rows


def build_scenes(root):
    txt = read(os.path.join(root, "ProjectSettings", "EditorBuildSettings.asset")) or ""
    out = []
    for en, path in re.findall(r"-\s*enabled:\s*(\d)\s*\n\s*path:\s*(.*)", txt):
        out.append({"enabled": en == "1", "path": path.strip()})
    return out


def assets_tree(root, excludes):
    base = os.path.join(root, "Assets")
    lines = ["Assets/"]

    def children(path):
        try:
            names = sorted(n for n in os.listdir(path)
                           if os.path.isdir(os.path.join(path, n)) and not n.startswith(".") and not n.endswith("~"))
        except OSError:
            return []
        return names

    for d1 in children(base):
        if d1 in excludes:
            continue
        lines.append("  " + d1 + "/")
        kids = [k for k in children(os.path.join(base, d1)) if (d1 + "/" + k) not in excludes]
        for k in kids[:TREE_CHILD_CAP]:
            lines.append("    " + k + "/")
        if len(kids) > TREE_CHILD_CAP:
            lines.append("    ... (+%d more)" % (len(kids) - TREE_CHILD_CAP))
    return lines


def collect(root, excludes):
    gidx = GuidIndex(root)
    ps = player_settings(root)
    pkgs, regs = packages(root)
    return {
        "root": root,
        "unity": unity_version(root),
        "product": ps["product"],
        "company": ps["company"],
        "input": ps["input"],
        "pipeline": render_pipeline(root, gidx),
        "packages": pkgs,
        "registries": regs,
        "asmdefs": asmdefs(root),
        "scenes": build_scenes(root),
        "tree": assets_tree(root, excludes),
    }


def facts_lines(f):
    p = f["pipeline"]
    out = [
        "- Unity: " + f["unity"],
        "- Product / company: %s / %s" % (f["product"], f["company"]),
        "- Active input handling: " + f["input"],
        "- Render pipeline default (GraphicsSettings): " + p["default"],
    ]
    for asset, names in p["by_asset"].items():
        out.append("- Render pipeline for quality [%s]: %s" % (", ".join(names), asset))
    out.append("- Current quality level: %s (%d levels)" % (p["quality_current"], p["quality_levels"]))
    for path, kind in p["renderers"]:
        out.append("- Renderer data: %s (%s)" % (path, kind))
    if f["registries"]:
        out.append("- Scoped registries: " + "; ".join(f["registries"]))
    return out


def render_block(f):
    L = [BEGIN, "### Snapshot facts"]
    L += facts_lines(f)
    L += ["", "#### Packages (manifest -> lock)", "| Package | Requested | Resolved | Source |", "|---|---|---|---|"]
    for r in f["packages"]:
        L.append("| %s | %s | %s | %s |" % (r["name"], r["requested"], r["resolved"], r["source"]))
    L += ["", "#### Assembly definitions", "| Assembly | Folder | Kind |", "|---|---|---|"]
    for r in f["asmdefs"]:
        L.append("| %s | %s | %s |" % (r["name"], r["folder"], r["kind"]))
    if not f["asmdefs"]:
        L.append("| (none: everything compiles into Assembly-CSharp) | - | - |")
    L += ["", "#### Scenes in build (EditorBuildSettings)"]
    for i, s in enumerate(f["scenes"]):
        L.append("%d. [%s] %s" % (i, "x" if s["enabled"] else " ", s["path"]))
    if not f["scenes"]:
        L.append("(none)")
    L += ["", "#### Assets layout (depth 2)", "```"] + f["tree"] + ["```", END]
    return "\n".join(L)


# ---------- parsing a stored block ----------

def extract_block(text):
    b = BEGIN_RE.search(text)
    e = END_RE.search(text)
    if not b or not e or e.start() < b.end():
        return None, None, None
    return text[b.end():e.start()], b.start(), e.end()


def parse_block(block):
    res = {"facts": {}, "packages": {}, "asmdefs": {}, "scenes": [], "tree": set()}
    section = "facts"
    in_fence = False
    for raw in block.splitlines():
        line = raw.rstrip()
        if line.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            if line.strip():
                res["tree"].add(line)
            continue
        if line.startswith("#### "):
            low = line.lower()
            section = ("packages" if "package" in low else "asmdefs" if "assembly" in low
                       else "scenes" if "scene" in low else "tree" if "layout" in low else "other")
            continue
        if section == "facts" and line.startswith("- ") and ":" in line:
            k, v = line[2:].split(":", 1)
            res["facts"][k.strip()] = v.strip()
        elif section in ("packages", "asmdefs") and line.startswith("|") and not line.startswith("|---"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if cells and cells[0] in ("Package", "Assembly"):
                continue
            if section == "packages" and len(cells) >= 4:
                res["packages"][cells[0]] = (cells[1], cells[2])
            elif section == "asmdefs" and len(cells) >= 3 and not cells[0].startswith("(none"):
                res["asmdefs"][cells[0]] = (cells[1], cells[2])
        elif section == "scenes":
            m = re.match(r"\d+\.\s*\[(x| )\]\s*(.+)", line)
            if m:
                res["scenes"].append((m.group(1) == "x", m.group(2).strip()))
    return res


def norm_resolved(v):
    m = re.search(r"@([0-9a-f]{7,})", v)
    return "@" + m.group(1)[:8] if m else v


def compare(stored, fresh_facts):
    cur = parse_block(render_block(fresh_facts))
    drift = []
    for k in sorted(set(stored["facts"]) | set(cur["facts"])):
        a, b = stored["facts"].get(k), cur["facts"].get(k)
        if a != b:
            drift.append("facts: '%s' PROJECT.md=%s project=%s" % (k, a or "(missing)", b or "(missing)"))
    for name in sorted(set(stored["packages"]) | set(cur["packages"])):
        a, b = stored["packages"].get(name), cur["packages"].get(name)
        if a is None:
            drift.append("packages: %s %s is in the project but not in PROJECT.md" % (name, b[1]))
        elif b is None:
            drift.append("packages: %s is in PROJECT.md but no longer in manifest.json" % name)
        elif a[0] != b[0] or norm_resolved(a[1]) != norm_resolved(b[1]):
            drift.append("packages: %s PROJECT.md=%s/%s project=%s/%s" % (name, a[0], a[1], b[0], b[1]))
    for name in sorted(set(stored["asmdefs"]) | set(cur["asmdefs"])):
        a, b = stored["asmdefs"].get(name), cur["asmdefs"].get(name)
        if a != b:
            drift.append("asmdefs: %s PROJECT.md=%s project=%s" % (name, a or "(missing)", b or "(missing)"))
    if stored["scenes"] != cur["scenes"]:
        drift.append("scenes: PROJECT.md=%s project=%s" % (
            [("" if e else "(off) ") + p for e, p in stored["scenes"]],
            [("" if e else "(off) ") + p for e, p in cur["scenes"]]))
    added, removed = cur["tree"] - stored["tree"], stored["tree"] - cur["tree"]
    if added or removed:
        drift.append("layout: added %s removed %s" % (sorted(s.strip() for s in added), sorted(s.strip() for s in removed)))
    return drift


def section_of(lines):
    """Map line index -> current '## ' heading (lowercase)."""
    out, cur = [], ""
    for ln in lines:
        if ln.startswith("## "):
            cur = ln[3:].strip().lower()
        out.append(cur)
    return out


def doc_warnings(text, facts, root, max_lines, doc_dir):
    warns, fails = [], []
    lines = text.splitlines()
    blk = extract_block(text)[0]
    prose = len(lines) - (len(blk.splitlines()) + 1 if blk is not None else 0)
    if prose > max_lines:
        warns.append("PROJECT.md has %d hand-written lines outside the snapshot (limit ~%d): move detail to linked docs"
                     % (prose, max_lines))
    for i, ln in enumerate(lines, 1):
        for pat in SECRET_PATTERNS:
            if pat.search(ln):
                fails.append("possible secret on line %d: %s" % (i, ln.strip()[:60]))
                break
    heads = [l[3:].strip().lower() for l in lines if l.startswith("## ")]
    for need in ("current milestone", "build and test", "conventions", "folder layout",
                 "architecture decisions", "known gotchas"):
        if not any(h.startswith(need) for h in heads):
            warns.append("missing section '## %s'" % need.title())
    # milestone pointer -> backlog file and id
    m = re.search(r"Current milestone:\s*(M\d+)\b[^\n]*?\(([^)#\s]+\.md)", text)
    if not m:
        warns.append("no 'Current milestone: M<n> ... (BACKLOG.md#...)' pointer")
    else:
        mid, bl = m.group(1), m.group(2)
        blp = os.path.join(doc_dir, bl)
        if not os.path.isfile(blp):
            blp = os.path.join(root, bl)
        if not os.path.isfile(blp):
            warns.append("milestone pointer names %s but %s does not exist" % (bl, blp))
        elif not re.search(r"^##\s+" + re.escape(mid) + r"\b", read(blp) or "", re.M):
            warns.append("milestone %s not found as a '## %s' heading in %s" % (mid, mid, bl))
    # manifest asks for a version the lock file has not resolved yet
    for r in facts["packages"]:
        if r["source"] in ("registry", "builtin") and r["requested"] != r["resolved"]:
            warns.append("manifest.json asks %s %s but packages-lock.json has %s: let Unity resolve "
                         "(open the editor or manage_packages resolve_packages), then --update"
                         % (r["name"], r["requested"], r["resolved"]))
    block_txt, bstart, bend = extract_block(text)
    pk = {r["name"]: r["resolved"] for r in facts["packages"]}
    req = {r["name"]: str(r["requested"]) for r in facts["packages"]}
    uver = facts["unity"].split()[0]
    # stale version mentions outside the generated block, ADRs and changelog
    secs = section_of(lines)
    pos = 0
    for i, ln in enumerate(lines):
        start = pos
        pos += len(ln) + 1
        if bstart is not None and bstart <= start < bend:
            continue
        if secs[i].startswith("architecture decisions") or secs[i].startswith("changelog"):
            continue
        for name, ver in re.findall(r"(com\.[a-z0-9][a-z0-9.\-]*[a-z0-9])[ @:=]+v?(\d+\.\d+\.\d+[0-9A-Za-z.\-]*)", ln):
            ver = ver.rstrip(".-")
            if name in pk and ver not in (pk[name].split(" ")[0], req[name]):
                warns.append("line %d mentions %s %s but the project resolves %s" % (i + 1, name, ver, pk[name]))
        for v in re.findall(r"\b(6000\.\d+\.\d+[abfp]\d+)\b", ln):
            if v != uver:
                warns.append("line %d mentions Unity %s but ProjectVersion.txt says %s" % (i + 1, v, uver))
    return warns, fails


def template_path():
    here = os.path.dirname(os.path.abspath(__file__))
    return os.path.join(os.path.dirname(here), "references", "PROJECT.template.md")


def main():
    ap = argparse.ArgumentParser(
        description="Print / check / refresh the generated facts block of PROJECT.md for a Unity project.",
        epilog="Examples:\n"
               "  project_snapshot.py --project ~/Game               # print block to paste\n"
               "  project_snapshot.py --project ~/Game --init        # create PROJECT.md from template\n"
               "  project_snapshot.py --project ~/Game --update      # refresh block in PROJECT.md\n"
               "  project_snapshot.py --project ~/Game --check       # exit 1 + RESULT: DRIFT n if stale\n",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=".", help="Unity project root or any folder inside it (default: cwd)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--json", action="store_true", help="print facts as JSON")
    g.add_argument("--check", nargs="?", const="", metavar="FILE", help="check FILE (default <root>/PROJECT.md) for drift")
    g.add_argument("--update", nargs="?", const="", metavar="FILE", help="rewrite the generated block in FILE")
    g.add_argument("--init", nargs="?", const="", metavar="FILE", help="create FILE from the template (no overwrite)")
    ap.add_argument("--exclude", action="append", default=[], metavar="DIR",
                    help="extra Assets folder to hide from the layout tree (name or Parent/Child); repeatable")
    ap.add_argument("--max-lines", type=int, default=200,
                    help="budget for hand-written lines outside the generated block (default 200)")
    ap.add_argument("--strict", action="store_true", help="--check: treat warnings as drift")
    a = ap.parse_args()

    root = find_root(a.project)
    if not root:
        fail("no ProjectSettings/ProjectVersion.txt at or above %s (not a Unity project)" % os.path.abspath(a.project))
    facts = collect(root, set(DEFAULT_TREE_EXCLUDES + a.exclude))
    block = render_block(facts)

    def target(v):
        return os.path.abspath(v) if v else os.path.join(root, "PROJECT.md")

    if a.json:
        out = dict(facts)
        out["pipeline"] = dict(facts["pipeline"], renderers=[{"path": p, "kind": k} for p, k in facts["pipeline"]["renderers"]])
        print(json.dumps(out, indent=2))
        print("RESULT: OK")
        return 0

    if a.init is not None:
        path = target(a.init)
        if os.path.exists(path):
            fail("%s exists; use --update to refresh its block" % path)
        tpl = read(template_path())
        if tpl is None:
            fail("template not found: " + template_path())
        _, bs, be = extract_block(tpl)
        if bs is None:
            fail("template has no project-snapshot markers")
        body = tpl[:bs] + block + tpl[be:]
        body = body.replace("{{UNITY_VERSION}}", facts["unity"].split()[0]).replace("{{PRODUCT}}", facts["product"])
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(body)
        print("wrote " + path)
        print("RESULT: OK")
        return 0

    if a.update is not None:
        path = target(a.update)
        text = read(path)
        if text is None:
            fail("%s not found (use --init)" % path)
        _, bs, be = extract_block(text)
        if bs is None:
            fail("%s has no project-snapshot markers; paste the default output once under '## Snapshot'" % path)
        new = text[:bs] + block + text[be:]
        if new != text:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(new)
            print("updated block in " + path)
        else:
            print("block already current in " + path)
        print("RESULT: OK")
        return 0

    if a.check is not None:
        path = target(a.check)
        text = read(path)
        if text is None:
            fail("%s not found (create it with --init)" % path, 1)
        stored_txt, _, _ = extract_block(text)
        if stored_txt is None:
            print("DRIFT no project-snapshot block in %s" % path)
            print("RESULT: DRIFT 1 (run --update after pasting the markers, or --init)")
            return 1
        drift = compare(parse_block(stored_txt), facts)
        warns, fails = doc_warnings(text, facts, root, a.max_lines, os.path.dirname(path))
        for d in drift:
            print("DRIFT " + d)
        for w in warns:
            print("WARN " + w)
        for f in fails:
            print("FAIL " + f)
        n = len(drift) + (len(warns) if a.strict else 0)
        if fails:
            print("RESULT: FAIL %d secret-like line(s); remove them from PROJECT.md" % len(fails))
            return 1
        if n:
            print("RESULT: DRIFT %d (refresh: project_snapshot.py --project %s --update)" % (n, root))
            return 1
        print("checked %s against %s (%d packages, %d asmdefs, %d build scenes, %d warnings)" % (
            path, root, len(facts["packages"]), len(facts["asmdefs"]), len(facts["scenes"]), len(warns)))
        print("RESULT: OK")
        return 0

    print(block)
    return 0


